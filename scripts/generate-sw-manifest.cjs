const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'sw-assets.js');
const checkOnly = process.argv.includes('--check');

function cleanReference(value) {
  if (!value || /^(?:https?:|data:|blob:|#)/i.test(value)) return null;
  const withoutQuery = value.split(/[?#]/, 1)[0].replace(/^\.\//, '');
  if (!withoutQuery || withoutQuery === '/') return null;
  return withoutQuery.replace(/^\//, '').replace(/\\/g, '/');
}

function collectTagReferences(html) {
  const results = [];
  const pattern = /<(?:link|script)\b[^>]*?\b(?:href|src)=["']([^"']+)["'][^>]*>/gi;
  for (const match of html.matchAll(pattern)) {
    const reference = cleanReference(match[1]);
    if (reference) results.push(reference);
  }
  return results;
}

function collectCssReferences(css) {
  const results = [];
  const pattern = /url\(\s*["']?([^"')]+)["']?\s*\)/gi;
  for (const match of css.matchAll(pattern)) {
    const reference = cleanReference(match[1]);
    if (reference) results.push(reference);
  }
  return results;
}

function assertLocalFile(relativePath, source) {
  const absolutePath = path.resolve(root, relativePath);
  if (!absolutePath.startsWith(root + path.sep) || !fs.existsSync(absolutePath) || !fs.statSync(absolutePath).isFile()) {
    throw new Error(`Missing local asset referenced by ${source}: ${relativePath}`);
  }
  return absolutePath;
}

const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const assetSet = new Set(['index.html', 'manifest.json']);
const dynamicPrintAssets = [
  'auris-print-qr.css', 'auris-print-noise-survey.css', 'auris-print-sop-editor.css',
  'auris-print-sop-saved.css', 'auris-print-swms.css', 'auris-print-incident.css',
  'auris-print-legal-register.css', 'auris-print-legal-change.css',
  'auris-print-toolbox-talk.css', 'auris-print-risk-assessment.css',
  'auris-print-fire-layout.css', 'auris-print-site-map.css'
];
for (const asset of dynamicPrintAssets) assetSet.add(asset);

for (const reference of collectTagReferences(html)) assetSet.add(reference);
for (const icon of manifest.icons || []) {
  const reference = cleanReference(icon.src);
  if (reference) assetSet.add(reference);
}

// CSS can introduce same-origin image/font dependencies that are invisible in index.html.
for (const relativePath of [...assetSet]) {
  if (!relativePath.endsWith('.css')) continue;
  const absolutePath = assertLocalFile(relativePath, 'index.html');
  for (const cssReference of collectCssReferences(fs.readFileSync(absolutePath, 'utf8'))) {
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(relativePath), cssReference));
    assetSet.add(resolved);
  }
}

const files = [...assetSet].sort();
const hash = crypto.createHash('sha256');
for (const relativePath of files) {
  const absolutePath = assertLocalFile(relativePath, relativePath === 'manifest.json' ? 'app shell' : 'index.html/CSS');
  hash.update(relativePath);
  hash.update('\0');
  hash.update(fs.readFileSync(absolutePath));
  hash.update('\0');
}

const generated = [
  '// Generated by scripts/generate-sw-manifest.cjs. Do not edit manually.',
  'self.AURIS_SW_ASSET_MANIFEST = ' + JSON.stringify({
    version: hash.digest('hex').slice(0, 16),
    assets: ['/', ...files.map((file) => '/' + file)]
  }, null, 2) + ';',
  ''
].join('\n');

if (checkOnly) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) {
    console.error('sw-assets.js is stale. Run: npm run generate:sw-manifest');
    process.exit(1);
  }
  console.log(`Offline asset manifest is current (${files.length + 1} routes).`);
} else {
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log(`Generated sw-assets.js with ${files.length + 1} routes.`);
}
